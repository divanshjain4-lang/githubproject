from app.core.segmentation_rules import classify_account_type
from app.services.model_service import predict_with_model
from app.schemas.customer import SegmentationRequest, SegmentationResponse

MODEL_VERSION = "rules-0.1.0"


def segment_customer(customer: SegmentationRequest) -> SegmentationResponse:
    model_prediction = predict_with_model(customer)
    if model_prediction is not None:
        segment, confidence = model_prediction
        return SegmentationResponse(
            customer_id=customer.customer_id,
            segment=segment,
            confidence=confidence,
            rationale=["Segment generated by the locally trained ML model"],
            model_version="ml-0.1.0",
            scoring_mode="ml",
        )

    result = classify_account_type(customer.account_type, customer.product_codes)
    rationale = result.rationale.copy()

    if customer.relationship_tenure_months is not None:
        rationale.append(f"Relationship tenure provided: {customer.relationship_tenure_months} months")
    if customer.interaction_text:
        rationale.append("Interaction text accepted for future NLP enrichment; not used by rules model")

    return SegmentationResponse(
        customer_id=customer.customer_id,
        segment=result.segment,
        confidence=result.confidence,
        rationale=rationale,
        model_version=MODEL_VERSION,
        scoring_mode="rules",
    )
